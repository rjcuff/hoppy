//! Who made a device, guessed from its MAC address.
//!
//! The first three bytes of a MAC address are assigned to a manufacturer.
//! The full registry is tens of thousands of entries; this is a short list of
//! makers that turn up on home, office, and AV networks.

/// `aa:bb:cc:dd:ee:ff`
pub fn format_mac(mac: [u8; 6]) -> String {
    mac.map(|byte| format!("{byte:02x}")).join(":")
}

/// Phones and laptops often invent a random MAC per network for privacy.
/// Those have the "locally administered" bit set and no real manufacturer.
pub fn is_private(mac: [u8; 6]) -> bool {
    mac[0] & 0b10 != 0
}

/// The maker of a device, when its prefix is on the list.
pub fn vendor(mac: [u8; 6]) -> Option<&'static str> {
    // Virtual adapters that use locally administered prefixes by convention.
    match mac {
        [0x02, 0x42, ..] => return Some("Docker"),
        [0x52, 0x54, 0x00, ..] => return Some("QEMU/KVM"),
        _ => {}
    }
    if is_private(mac) {
        return Some("private address");
    }

    let name = match [mac[0], mac[1], mac[2]] {
        [0x00, 0x03, 0x93]
        | [0x00, 0x0a, 0x95]
        | [0x00, 0x17, 0xf2]
        | [0x00, 0x1b, 0x63]
        | [0x00, 0x25, 0x00]
        | [0x28, 0xcf, 0xe9]
        | [0x3c, 0x07, 0x54]
        | [0x3c, 0x22, 0xfb]
        | [0xa4, 0x5e, 0x60]
        | [0xa4, 0x83, 0xe7]
        | [0xac, 0xbc, 0x32]
        | [0xf0, 0x18, 0x98] => "Apple",
        [0x44, 0x65, 0x0d]
        | [0x40, 0xb4, 0xcd]
        | [0x68, 0x54, 0xfd]
        | [0x74, 0xc2, 0x46]
        | [0xf0, 0x27, 0x2d]
        | [0xfc, 0x65, 0xde] => "Amazon",
        [0x00, 0x1d, 0xc1] => "Audinate (Dante)",
        [0x00, 0x80, 0x77] | [0x00, 0x1b, 0xa9] => "Brother",
        [0x18, 0xfe, 0x34]
        | [0x24, 0x0a, 0xc4]
        | [0x24, 0x6f, 0x28]
        | [0x30, 0xae, 0xa4]
        | [0x3c, 0x71, 0xbf]
        | [0x5c, 0xcf, 0x7f]
        | [0x60, 0x01, 0x94]
        | [0x84, 0xcc, 0xa8]
        | [0x8c, 0xaa, 0xb5]
        | [0xa4, 0xcf, 0x12]
        | [0xec, 0xfa, 0xbc] => "Espressif (smart device)",
        [0x00, 0x1a, 0x11]
        | [0x18, 0xb4, 0x30]
        | [0x3c, 0x5a, 0xb4]
        | [0x54, 0x60, 0x09]
        | [0x64, 0x16, 0x66]
        | [0xf4, 0xf5, 0xd8] => "Google/Nest",
        [0x00, 0x15, 0x5d] => "Hyper-V",
        [0x00, 0x18, 0x0a] => "Cisco Meraki",
        [0x00, 0x0c, 0x42]
        | [0x48, 0x8f, 0x5a]
        | [0x4c, 0x5e, 0x0c]
        | [0x64, 0xd1, 0x54]
        | [0x6c, 0x3b, 0x6b]
        | [0x74, 0x4d, 0x28]
        | [0xb8, 0x69, 0xf4]
        | [0xcc, 0x2d, 0xe0]
        | [0xd4, 0xca, 0x6d]
        | [0xe4, 0x8d, 0x8c] => "MikroTik",
        [0x00, 0x14, 0x6c] | [0x20, 0xe5, 0x2a] | [0xa0, 0x40, 0xa0] | [0xc0, 0x3f, 0x0e] => {
            "Netgear"
        }
        [0x00, 0x1c, 0x42] => "Parallels",
        [0x00, 0x17, 0x88] | [0xec, 0xb5, 0xfa] => "Philips Hue",
        [0x00, 0x08, 0x9b] | [0x24, 0x5e, 0xbe] => "QNAP",
        [0x28, 0xcd, 0xc1]
        | [0x2c, 0xcf, 0x67]
        | [0xb8, 0x27, 0xeb]
        | [0xd8, 0x3a, 0xdd]
        | [0xdc, 0xa6, 0x32]
        | [0xe4, 0x5f, 0x01] => "Raspberry Pi",
        [0x08, 0x05, 0x81] | [0xb0, 0xa7, 0x37] | [0xcc, 0x6d, 0xa0] | [0xdc, 0x3a, 0x5e] => "Roku",
        [0x00, 0x0e, 0x58]
        | [0x5c, 0xaa, 0xfd]
        | [0x78, 0x28, 0xca]
        | [0x94, 0x9f, 0x3e]
        | [0xb8, 0xe9, 0x37] => "Sonos",
        [0x00, 0x11, 0x32] => "Synology",
        [0x14, 0xcc, 0x20]
        | [0x50, 0xc7, 0xbf]
        | [0x98, 0xda, 0xc4]
        | [0xac, 0x84, 0xc6]
        | [0xb0, 0x4e, 0x26]
        | [0xf4, 0xf2, 0x6d] => "TP-Link",
        [0x04, 0x18, 0xd6]
        | [0x18, 0xe8, 0x29]
        | [0x24, 0xa4, 0x3c]
        | [0x68, 0xd7, 0x9a]
        | [0x74, 0x83, 0xc2]
        | [0x78, 0x8a, 0x20]
        | [0x80, 0x2a, 0xa8]
        | [0xb4, 0xfb, 0xe4]
        | [0xf0, 0x9f, 0xc2]
        | [0xfc, 0xec, 0xda] => "Ubiquiti",
        [0x08, 0x00, 0x27] => "VirtualBox",
        [0x00, 0x05, 0x69] | [0x00, 0x0c, 0x29] | [0x00, 0x50, 0x56] => "VMware",
        [0x00, 0x16, 0x3e] => "Xen",
        _ => return None,
    };
    Some(name)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn formats_lowercase_with_colons() {
        assert_eq!(
            format_mac([0xB8, 0x27, 0xEB, 0x00, 0x0a, 0xff]),
            "b8:27:eb:00:0a:ff"
        );
    }

    #[test]
    fn names_known_makers() {
        assert_eq!(vendor([0xb8, 0x27, 0xeb, 1, 2, 3]), Some("Raspberry Pi"));
        assert_eq!(
            vendor([0x00, 0x1d, 0xc1, 1, 2, 3]),
            Some("Audinate (Dante)")
        );
        assert_eq!(vendor([0x00, 0x11, 0x32, 1, 2, 3]), Some("Synology"));
        assert_eq!(vendor([0x10, 0x20, 0x30, 1, 2, 3]), None);
    }

    #[test]
    fn random_macs_are_called_private() {
        assert!(is_private([0xda, 0xa1, 0x19, 0, 0, 1]));
        assert!(!is_private([0xb8, 0x27, 0xeb, 0, 0, 1]));
        assert_eq!(vendor([0xda, 0xa1, 0x19, 0, 0, 1]), Some("private address"));
    }

    #[test]
    fn virtual_prefixes_beat_the_private_bit() {
        assert_eq!(vendor([0x02, 0x42, 0xac, 0x11, 0, 2]), Some("Docker"));
        assert_eq!(vendor([0x52, 0x54, 0x00, 1, 2, 3]), Some("QEMU/KVM"));
    }
}
